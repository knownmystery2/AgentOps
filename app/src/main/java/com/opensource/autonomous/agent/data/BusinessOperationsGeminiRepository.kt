    /**
     * Resolves the active Gemini API key from SecretManager or BuildConfig.
     */
    fun resolveGeminiApiKey(): String {
        val managerKey = secretManager?.getGeminiApiKey()?.trim().orEmpty()
        if (managerKey.isNotBlank()) return managerKey

        val buildConfigKey = try {
            BuildConfig.GEMINI_API_KEY.trim()
        } catch (_: Throwable) {
            ""
        }
        if (buildConfigKey.isNotBlank() && !buildConfigKey.startsWith("placeholder_")) {
            return buildConfigKey
        }
        return ""
    }

    /**
     * Checks if a valid Gemini API key is configured.
     */
    fun isGeminiConfigured(): Boolean = resolveGeminiApiKey().isNotBlank()

    /**
     * Processes a natural language business input, passing it through Gemini
     * to formulate executive business operations and prioritized agent task suggestions.
     */
    /**
     * Processes a natural language business input, passing it through Gemini
     * to formulate executive business operations and prioritized agent task suggestions.
     * Supports optional tool execution (RepositoryTool) and multi-model fallback.
     */
    suspend fun processBusinessPrompt(
        inputPrompt: String,
        contextData: BusinessContext = BusinessContext(),
        modelName: String = defaultModelName,
        enableTools: Boolean = false
    ): Result<BusinessOperationsAnalysis> = withContext(Dispatchers.IO) {
        val trimmedPrompt = inputPrompt.trim()
        if (trimmedPrompt.isBlank()) {
            return@withContext Result.failure(IllegalArgumentException("Operational prompt cannot be empty."))
        }

        val apiKey = resolveGeminiApiKey()
        if (apiKey.isBlank()) {
            Log.w(TAG, "Gemini API key not found; utilizing built-in deterministic business reasoning fallback.")
            val fallbackResult = generateDeterministicFallback(trimmedPrompt, contextData)
            return@withContext Result.success(fallbackResult)
        }

        val fullUserPayload = """
OPERATIONAL REQUEST FROM FOUNDER:
"$trimmedPrompt"

BUSINESS CONTEXT:
- Storefront Theme: ${contextData.storeTheme}
- Target Niche: ${contextData.targetNiche}
- Primary Storefront / Shop Domain: ${contextData.primaryShopDomain}
- Current Catalog Items: ${contextData.currentCatalogCount}
- Double-Entry Ledger Balanced: ${contextData.doubleEntryLedgerBalanced}
- Zero Upfront Cost Mandate: ${contextData.zeroCostMandateActive}

Decompose this operational request into prioritized, high-margin task suggestions for our autonomous agents.
Respond strictly in JSON adhering to the specified schema.
""".trimIndent()

        // Helper to attempt model invocation with given model name
        suspend fun attemptGeminiCall(targetModel: String): String? {
            return try {
                val genModel = GenerativeModel(
                    modelName = targetModel,
                    apiKey = apiKey,
                    generationConfig = generationConfig {
                        temperature = 0.2f
                        topP = 0.95f
                        responseMimeType = if (enableTools) null else "application/json"
                    },
                    systemInstruction = content { text(SYSTEM_INSTRUCTION) },
                    tools = if (enableTools) listOf(repoTool) else null
                )

                if (enableTools) {
                    val chat = genModel.startChat()
                    var chatResponse = chat.sendMessage(fullUserPayload)
                    val functionCall = chatResponse.functionCalls.firstOrNull()
                    if (functionCall != null && functionCall.name == "readRepositoryFile") {
                        val filePath = (functionCall.args["filePath"] ?: "") as String
                        val fileContent = readRepositoryFile(filePath)
                        chatResponse = chat.sendMessage(
                            RepoToolGenerativeModel.FunctionResponse(
                                name = "readRepositoryFile",
                                response = mapOf("content" to fileContent)
                            )
                        )
                    }
                    chatResponse.text?.trim()
                } else {
                    val response = genModel.generateContent(fullUserPayload)
                    response.text?.trim()
                }
            } catch (e: Exception) {
                Log.w(TAG, "Gemini invocation failed with model $targetModel: ${e.message}")
                null
            }
        }

        // Try user/default model first, then fallback model if primary fails
        var rawJsonText = attemptGeminiCall(modelName)
        var usedModel = modelName

        if (rawJsonText.isNullOrBlank() && modelName != "gemini-2.5-flash") {
            Log.i(TAG, "Attempting fallback to gemini-2.5-flash...")
            rawJsonText = attemptGeminiCall("gemini-2.5-flash")
            if (!rawJsonText.isNullOrBlank()) {
                usedModel = "gemini-2.5-flash"
            }
        }

        if (rawJsonText.isNullOrBlank()) {
            Log.w(TAG, "Gemini online calls unavailable, falling back to local business operations engine.")
            val fallback = generateDeterministicFallback(trimmedPrompt, contextData)
            return@withContext Result.success(fallback)
        }

        val parsed = parseGeminiResponse(rawJsonText, trimmedPrompt).copy(modelUsed = usedModel)

        // Log successful reasoning into audit trail
        db.logDao().insertLog(
            LogEntity(
                agentId = "Administrator AI",
                message = "Gemini ($usedModel) processed business prompt: '${trimmedPrompt.take(50)}...' -> Generated ${parsed.taskSuggestions.size} task suggestions.",
                timestamp = System.currentTimeMillis()
            )
        )

        Result.success(parsed)
    }

    /**
     * Executes a prompt with repository file reading tool support (Function Calling).
     * Connects natural language developer prompts to local repository inspection.
     */
    suspend fun processPromptWithRepositoryTool(
        prompt: String = "Check my src/Main.kt file for errors."
    ): String? = withContext(Dispatchers.IO) {
        val apiKey = resolveGeminiApiKey()
        if (apiKey.isBlank()) {
            return@withContext "Error: Gemini API key not configured."
        }

        try {
            val genModel = GenerativeModel(
                modelName = defaultModelName,
                apiKey = apiKey,
                tools = listOf(repoTool)
            )
            val chat = genModel.startChat()
            val response = chat.sendMessage(prompt)

            val functionCall = response.functionCalls.firstOrNull()
            if (functionCall != null && functionCall.name == "readRepositoryFile") {
                val filePath = (functionCall.args["filePath"] ?: "") as String
                val fileContent = readRepositoryFile(filePath)
                val finalResponse = chat.sendMessage(
                    RepoToolGenerativeModel.FunctionResponse(
                        name = "readRepositoryFile",
                        response = mapOf("content" to fileContent)
                    )
                )
                finalResponse.text
            } else {
                response.text
            }
        } catch (e: Exception) {
            Log.e(TAG, "Tool calling failed: ${e.message}", e)
            "Error executing tool prompt: ${e.message}"
        }
    }

