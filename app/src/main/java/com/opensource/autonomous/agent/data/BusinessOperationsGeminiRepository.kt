    /**
     * Executes the suggested business action directly or routes it to the appropriate subsystem.
     */
    suspend fun executeSuggestedBusinessAction(suggestion: BusinessTaskSuggestion): Result<String> = withContext(Dispatchers.IO) {
        try {
            when (suggestion.suggestedAction.uppercase()) {
                "CREATE_TASK" -> {
                    enqueueSuggestionAsActiveTask(suggestion)
                    Result.success("Task enqueued in active Swarm Queue for ${suggestion.assignedAgentRole}")
                }
                "DEPLOY_POD" -> {
                    enqueueSuggestionAsActiveTask(suggestion)
                    Result.success("POD blueprint routed to Creative Design Agent for Printify shop ${suggestion.targetResource}")
                }
                "DISPATCH_MARKETING" -> {
                    enqueueSuggestionAsActiveTask(suggestion)
                    Result.success("Marketing campaign dispatched to Organic Marketing Agent")
                }
                "AUDIT_LEDGER" -> {
                    enqueueSuggestionAsActiveTask(suggestion)
                    Result.success("Double-entry ledger audit routine initiated for whole-cent balance verification")
                }
                "AUDIT_TRADEMARK" -> {
                    enqueueSuggestionForHumanApproval(suggestion)
                    Result.success("Trademark clearance registered in Approval Register for founder confirmation")
                }
                else -> {
                    enqueueSuggestionAsActiveTask(suggestion)
                    Result.success("Operation '${suggestion.suggestedAction}' assigned to ${suggestion.assignedAgentRole}")
                }
            }
        } catch (e: Exception) {
            Result.failure(e)
        }
    }

    /**
     * Generates business task suggestions specifically tailored for a target niche and channel.
     */
    suspend fun suggestTasksForNiche(
        niche: String,
        targetPlatform: String = "Printify & Storefront"
    ): Result<List<BusinessTaskSuggestion>> = withContext(Dispatchers.IO) {
        val prompt = "Generate a comprehensive operational action plan to launch and scale products for the niche: '$niche' on platform: '$targetPlatform'."
        val analysis = processBusinessPrompt(prompt, BusinessContext(targetNiche = niche)).getOrNull()
        val suggestions = analysis?.taskSuggestions ?: emptyList()
        Result.success(suggestions)
    }

    /**
     * Enqueues a suggested business operation directly into the active Swarm Task Queue in Room.
     */
    suspend fun enqueueSuggestionAsActiveTask(suggestion: BusinessTaskSuggestion): TaskEntity = withContext(Dispatchers.IO) {
        val task = TaskEntity(
            id = suggestion.id,
            assignedToAgentId = suggestion.assignedAgentId,
            title = suggestion.title,
            instruction = "${suggestion.detailedInstruction}\n\nCategory: ${suggestion.category}\nPriority: ${suggestion.priority}\nEst. Margin: ${suggestion.estimatedMarginPercent}%\nZero Cost Compliance: ${suggestion.zeroCostCompliance}",
            status = "PENDING",
            result = null,
            timestamp = System.currentTimeMillis()
        )
        db.taskDao().insertTask(task)

        db.logDao().insertLog(
            LogEntity(
                agentId = suggestion.assignedAgentRole,
                message = "Task enqueued from Gemini business suggestion: '${suggestion.title}' (Priority: ${suggestion.priority})",
                timestamp = System.currentTimeMillis()
            )
        )

        task
    }

    /**
     * Enqueues a suggested business task into the Standby Pool Manager to run
     * when device battery and network constraints are satisfied.
     */
    fun enqueueSuggestionToStandbyPool(
        suggestion: BusinessTaskSuggestion,
        requiresWifi: Boolean = true,
        requiresCharging: Boolean = false
    ): String {
        val condition = com.opensource.autonomous.agent.engine.ExecutionCondition(
            requiresNetwork = requiresWifi,
            requiresCharging = requiresCharging
        )
        return standbyPoolManager?.queueStandbyTask(
            taskId = suggestion.id,
            agentId = suggestion.assignedAgentId,
            title = suggestion.title,
            instruction = suggestion.detailedInstruction,
            condition = condition
        )?.taskId ?: suggestion.id
    }

    /**
     * Creates a formal pending Decision in the Approval Register for human sign-off
     * before live execution or deployment.
     */
    suspend fun enqueueSuggestionForHumanApproval(suggestion: BusinessTaskSuggestion): DecisionEntity = withContext(Dispatchers.IO) {
        val decision = DecisionEntity(
            id = "DEC-" + suggestion.id.take(8).uppercase(),
            agentSource = suggestion.assignedAgentRole,
            description = "${suggestion.title} - ${suggestion.detailedInstruction}",
            payloadJson = gson.toJson(suggestion),
            status = "PENDING",
            timestamp = System.currentTimeMillis()
        )
        db.decisionDao().insertDecision(decision)

        db.logDao().insertLog(
            LogEntity(
                agentId = "Compliance Agent",
                message = "Business operation registered for human approval: '${suggestion.title}'",
                timestamp = System.currentTimeMillis()
            )
        )

        decision
    }

    /**
     * Robust parser for Gemini JSON responses, handling potential markdown code blocks.
     */
    private fun parseGeminiResponse(rawText: String, originalPrompt: String): BusinessOperationsAnalysis {
        val cleanJson = if (rawText.contains("```json")) {
            rawText.substringAfter("```json").substringBefore("```").trim()
        } else if (rawText.contains("```")) {
            rawText.substringAfter("```").substringBefore("```").trim()
        } else {
            rawText.trim()
        }

        return try {
            val root = JsonParser.parseString(cleanJson).asJsonObject
            val summary = root.get("executiveSummary")?.asString ?: "Operational analysis completed."
            val niche = root.get("nicheFocus")?.asString ?: "E-Commerce"
            val goalsList = mutableListOf<String>()
            root.getAsJsonArray("strategicGoals")?.forEach { elem ->
                goalsList.add(elem.asString)
            }

            val suggestionsList = mutableListOf<BusinessTaskSuggestion>()
            root.getAsJsonArray("taskSuggestions")?.forEach { elem ->
                if (elem.isJsonObject) {
                    val obj = elem.asJsonObject
                    val cat = obj.get("category")?.asString ?: "PRODUCT_DESIGN"
                    val agentId = obj.get("assignedAgentId")?.asString ?: mapCategoryToAgentId(cat)
                    val role = obj.get("assignedAgentRole")?.asString ?: mapAgentIdToRole(agentId)

                    suggestionsList.add(
                        BusinessTaskSuggestion(
                            title = obj.get("title")?.asString ?: "Autonomous Business Task",
                            category = cat,
                            assignedAgentId = agentId,
                            assignedAgentRole = role,
                            priority = obj.get("priority")?.asString ?: "MEDIUM",
                            detailedInstruction = obj.get("detailedInstruction")?.asString ?: "Execute autonomous operation.",
                            estimatedMarginPercent = obj.get("estimatedMarginPercent")?.asInt ?: 40,
                            zeroCostCompliance = obj.get("zeroCostCompliance")?.asBoolean ?: true,
                            suggestedAction = obj.get("suggestedAction")?.asString ?: "CREATE_TASK",
                            targetResource = obj.get("targetResource")?.asString ?: "storefront/catalog"
                        )
                    )
                }
            }

            val risk = root.get("riskAssessment")?.asString ?: "USPTO & $0 COGS verified safe."
            val nextStep = root.get("immediateNextStep")?.asString ?: "Dispatch tasks to agent swarm."

            BusinessOperationsAnalysis(
                rawPrompt = originalPrompt,
                executiveSummary = summary,
                nicheFocus = niche,
                strategicGoals = if (goalsList.isNotEmpty()) goalsList else listOf("Scale revenue with $0 upfront cost", "Maximize profit margins"),
                taskSuggestions = suggestionsList,
                riskAssessment = risk,
                immediateNextStep = nextStep,
                timestamp = System.currentTimeMillis()
            )
        } catch (e: Exception) {
            Log.w(TAG, "Failed to parse structured JSON from Gemini: ${e.message}, building structured payload from response.")
            generateDeterministicFallback(originalPrompt, BusinessContext())
        }
    }

